import { mkdir, mkdtemp, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';
import {
  applyArchipielagoUserConfig,
  resetArchipielagoConfig,
} from '@archipielago/core/config.js';
import { getArchipielagoPaths } from '@archipielago/core/paths.js';
import {
  discoverIslands,
  ManualRegistrationSyncError,
  renderIslandsGeneratedModule,
  syncIslandManifest,
} from './sync-island-manifest.js';

const tempDirs: string[] = [];

afterEach(async () => {
  resetArchipielagoConfig();
  const { rm } = await import('node:fs/promises');
  await Promise.all(
    tempDirs.splice(0).map((dir) => rm(dir, { recursive: true, force: true })),
  );
});

/**
 * Creates a temp repo root with an islands tree for sync tests.
 *
 * @returns {Promise<string>} Absolute temp root.
 */
async function tempRoot(): Promise<string> {
  const root = await mkdtemp(join(tmpdir(), 'island-sync-'));
  tempDirs.push(root);
  return root;
}

describe('discoverIslands', () => {
  it('keeps only dirname===basename .tsx entries and detects CSS modules', async () => {
    const root = await tempRoot();
    const islands = join(root, 'islands');
    await mkdir(join(islands, 'nav'), { recursive: true });
    await writeFile(
      join(islands, 'nav', 'nav.tsx'),
      'export default function N() {}',
    );
    await writeFile(join(islands, 'nav', 'nav.module.scss'), '.x{}');
    await mkdir(join(islands, 'plain'), { recursive: true });
    await writeFile(
      join(islands, 'plain', 'plain.tsx'),
      'export default function P() {}',
    );
    await mkdir(join(islands, '__screenshots__'), { recursive: true });
    await writeFile(join(islands, '__screenshots__', 'x.png'), '');
    await mkdir(join(islands, 'incomplete'), { recursive: true });
    await writeFile(join(islands, 'incomplete', 'index.ts'), 'export {}');

    const entries = await discoverIslands(islands);
    expect(entries).toEqual([
      { name: 'nav', hasCssModule: true },
      { name: 'plain', hasCssModule: false },
    ]);
  });
});

describe('renderIslandsGeneratedModule', () => {
  it('emits only the islands map (no helpers)', () => {
    const source = renderIslandsGeneratedModule([
      { name: 'b-island', hasCssModule: false },
      { name: 'a-island', hasCssModule: true },
    ]);
    expect(source).toContain('Generated by `pnpm islands:sync`');
    expect(source).toContain("'a-island': { hasCssModule: true }");
    expect(source).toContain("'b-island': { hasCssModule: false }");
    expect(source).toContain('export const islands = {');
    expect(source).not.toContain('islandCssModuleUrl');
    expect(source).not.toContain('IslandName');
    expect(source).not.toContain('islandEntryRelPath');
  });
});

describe('syncIslandManifest', () => {
  it('writes the configured islands map under the repo root', async () => {
    const root = await tempRoot();
    const islands = join(root, 'src/web/ui/islands');
    await mkdir(join(islands, 'widget'), { recursive: true });
    await writeFile(
      join(islands, 'widget', 'widget.tsx'),
      'export default function W() {}',
    );

    const { path, entries } = await syncIslandManifest(root);
    expect(path).toBe(join(root, getArchipielagoPaths().islandsGeneratedRel));
    expect(entries).toEqual([{ name: 'widget', hasCssModule: false }]);

    const { readFile } = await import('node:fs/promises');
    const written = await readFile(path, 'utf8');
    expect(written).toContain("'widget': { hasCssModule: false }");
    expect(written).not.toContain('function isIslandName');
  });

  it('refuses to write when registration is manual', async () => {
    applyArchipielagoUserConfig({
      islands: { registration: 'manual' },
    });
    const root = await tempRoot();

    await expect(syncIslandManifest(root)).rejects.toBeInstanceOf(
      ManualRegistrationSyncError,
    );
  });
});
