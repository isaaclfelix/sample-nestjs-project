/**
 * Scans conventional island folders and writes the host islands manifest.
 *
 * Convention (ADR-0025): `ui/islands/<name>/<name>.tsx` is a registered island;
 * optional `<name>.module.scss` sets `hasCssModule`. Only runs when
 * `archipielago.config.ts` sets `islands.registration: 'auto'` (default).
 * In `manual` mode this command refuses to write so authors keep ownership.
 *
 * Usage:
 *   pnpm islands:sync
 */
import { existsSync } from 'node:fs';
import { mkdir, readdir, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  getIslandsRegistration,
  loadAndApplyArchipielagoConfig,
} from '../src/archipielago/core/config.js';
import { getArchipielagoPaths } from '../src/archipielago/core/paths.js';

/** One discovered product island under `ui/islands/`. */
export interface IslandManifestEntry {
  name: string;
  hasCssModule: boolean;
}

/**
 * Error when sync is invoked while the host owns the islands manifest by hand.
 */
export class ManualRegistrationSyncError extends Error {
  /**
   * @param {string} message - Human-readable refusal.
   */
  constructor(message: string) {
    super(message);
    this.name = 'ManualRegistrationSyncError';
  }
}

/**
 * Lists island folders that follow `<name>/<name>.tsx`.
 *
 * Skips directories without the concrete implementation file (screenshots,
 * incomplete scaffolds, helpers).
 *
 * @param {string} islandsDir - Absolute path to the islands directory.
 * @returns {Promise<IslandManifestEntry[]>} Sorted entries (stable diffs).
 */
export async function discoverIslands(
  islandsDir: string,
): Promise<IslandManifestEntry[]> {
  if (!existsSync(islandsDir)) {
    return [];
  }

  const dirents = await readdir(islandsDir, { withFileTypes: true });
  const entries: IslandManifestEntry[] = [];

  for (const dirent of dirents) {
    if (!dirent.isDirectory()) {
      continue;
    }

    const name = dirent.name;
    // Concrete entry only — not the thin barrel (ADR-0025).
    const entryTsx = join(islandsDir, name, `${name}.tsx`);
    if (!existsSync(entryTsx)) {
      continue;
    }

    const cssModule = join(islandsDir, name, `${name}.module.scss`);
    entries.push({
      name,
      hasCssModule: existsSync(cssModule),
    });
  }

  entries.sort((a, b) => a.name.localeCompare(b.name));
  return entries;
}

/**
 * Renders only the generated `islands` map module.
 *
 * @param {IslandManifestEntry[]} entries - Discovered islands.
 * @returns {string} Full file contents for the islands map module.
 */
export function renderIslandsGeneratedModule(
  entries: IslandManifestEntry[],
): string {
  const rows = entries
    .map(
      (entry) =>
        `  '${entry.name}': { hasCssModule: ${String(entry.hasCssModule)} },`,
    )
    .join('\n');

  return `/**
 * Generated by \`pnpm islands:sync\` (islands.registration=auto).
 * Do not edit by hand — switch to registration=manual to own this file.
 *
 * Derived from conventional \`ui/islands/<name>/<name>.tsx\` (+ optional
 * \`<name>.module.scss\`). Injected via registerIslands — see ADR-0028 / 0030.
 */

/**
 * Registered product islands and whether each ships a CSS module.
 */
export const islands = {
${rows}
} as const;
`;
}

/**
 * Discovers islands under the repo and writes the configured islands manifest.
 *
 * Refuses when `islands.registration` is `manual` so sync never overwrites
 * a hand-maintained manifest. Call {@link loadAndApplyArchipielagoConfig} first
 * from CLI; tests may set registration via `applyArchipielagoUserConfig`.
 *
 * @param {string} rootDir - Repository root.
 * @returns {Promise<{ path: string; entries: IslandManifestEntry[] }>} Write result.
 * @throws {ManualRegistrationSyncError} When registration is `manual`.
 */
export async function syncIslandManifest(
  rootDir: string,
): Promise<{ path: string; entries: IslandManifestEntry[] }> {
  if (getIslandsRegistration() === 'manual') {
    const rel = getArchipielagoPaths().islandsGeneratedRel;
    throw new ManualRegistrationSyncError(
      `islands.registration=manual: refusing to overwrite ${rel}. ` +
        `Edit that file by hand (or set registration to auto). ` +
        `Remove islands:sync from package.json hooks if you switched modes.`,
    );
  }

  const paths = getArchipielagoPaths();
  const islandsDir = join(rootDir, paths.islandsDirRel);
  const outPath = join(rootDir, paths.islandsGeneratedRel);
  const entries = await discoverIslands(islandsDir);
  const source = renderIslandsGeneratedModule(entries);

  await mkdir(dirname(outPath), { recursive: true });
  await writeFile(outPath, source, 'utf8');

  return { path: outPath, entries };
}

/**
 * CLI entry: load host config, then sync from the repo root.
 *
 * @returns {Promise<void>}
 */
async function main(): Promise<void> {
  const rootDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
  await loadAndApplyArchipielagoConfig(rootDir);
  const { path, entries } = await syncIslandManifest(rootDir);
  const names = entries.map((entry) => entry.name).join(', ') || '(none)';
  process.stdout.write(
    `Wrote ${path} (${String(entries.length)} islands: ${names})\n`,
  );
}

const isDirectRun =
  process.argv[1] !== undefined &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (isDirectRun) {
  try {
    await main();
  } catch (error: unknown) {
    const message = error instanceof Error ? error.message : String(error);
    process.stderr.write(`${message}\n`);
    process.exitCode = 1;
  }
}
